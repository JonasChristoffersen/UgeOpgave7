public class Level1DelE {
    public void main() {
        //Del E: Working with char
        //Opgave 1.21: Char basics
        System.out.println("Opgave 1.21: Char basics");
        char initial = 'M';
        System.out.println(initial);
        initial = 'K';
        System.out.println(initial);

        //Opgave 1.22: Multiple chars
        System.out.println("Opgave 1.22: Multiple chars");
        char gradeA = 'A';
        char gradeB = 'B';
        char gradeC = 'C';
        System.out.println(gradeA);
        System.out.println(gradeB);
        System.out.println(gradeC);

        //Opgave 1.23: Char symbols
        System.out.println("Opgave 1.23: Char symbols");
        char star = '*';
        char plus = '=';
        char dollar = '$';
        System.out.println(star);
        System.out.println(plus);
        System.out.println(dollar);

        //Opgave 1.24: Char numbers
        System.out.println("Opgave 1.24: Char numbers");
        char digit = '5';
        System.out.println(digit);
        digit = '9';
        System.out.println(digit);

        //Opgave 1.25: Char vs String
        System.out.println("Opgave 1.25: Char vs String");
        char singleLetter = 'A';
        String singleLetterString = "A";
        System.out.println(singleLetter);
        System.out.println(singleLetterString);
    }
}
