public class Level1DelA {
    public void main(){
        //Del A: Declaration & Initialization
        //Opgave 1.1: Din første variabel
        System.out.println("Opgave 1.1: Din første variabel");
        int myAge;
        myAge = 24;
        System.out.println(myAge);

        //Opgave 1.2: Declaration og initialization separat
        System.out.println("Opgave 1.2: Declaration og initialization separat");
        int score;
        score = 100;
        System.out.println(score);

        //Opgave 1.3: Declaration på én linje
        System.out.println("Opgave 1.3: Declaration på én linje");
        double price = 49.99;
        System.out.println(price);

        //Opgave 1.4: Multiple variables
        System.out.println("Opgave 1.4: Multiple variables");
        int quantity = 5;
        double pricePerItem = 12.50;
        boolean inStock = true;
        System.out.println(quantity);
        System.out.println(pricePerItem);
        System.out.println(inStock);

        //Opgave 1.5: Char variable
        System.out.println("Opgave 1.5: Char variable");
        char grade = 'A';
        System.out.println(grade);
    }
}
