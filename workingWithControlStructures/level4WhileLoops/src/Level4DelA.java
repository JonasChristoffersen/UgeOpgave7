public class Level4DelA {
    public void main() {
        //Del A: Basic While Loops
        //Opgave 4.1: Dit første while loop
        System.out.println("Opgave 4.1: Dit første while loop");
        int i = 0;
        while (i < 5) {
            System.out.println(i);
            i++;
        }

        //Opgave 4.2: Count to 10
        System.out.println("Opgave 4.2: Count to 10");
        int i1 = 1;
        while (i1 <= 10) {
            System.out.println(i1);
            i1++;
        }

        //Opgave 4.3: Count by 2
        System.out.println("Opgave 4.3: Count by 2");
        int i2 = 0;
        while (i2 <= 20) {
            System.out.println(i2);
            i2 += 2;
        }
    }
}
