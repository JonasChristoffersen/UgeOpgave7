public class Level5DelA {
    public void main() {
        //Del A: Basic For Loops
        //Opgave 5.1: Dit første for loop
        System.out.println("Opgave 5.1: Dit første for loop");
        for (int i = 0; i < 10; i++ ) {
            System.out.println(i);
        }

        //Opgave 5.2: Count 1 to 10
        System.out.println("Opgave 5.2: Count 1 to 10");
        for (int i = 1; i <= 10; i++) {
            System.out.println(i);
        }

        //Opgave 5.3: Custom range
        System.out.println("Opgave 5.3: Custom range");
        for (int i = 5; i <= 15; i++) {
            System.out.println(i);
        }
    }
}
